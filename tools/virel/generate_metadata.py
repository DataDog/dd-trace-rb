from pathlib import Path


BASE = 1 << 30
TYPES = [
    ("LONG", "long", []),
    ("STRING", "virel.String", []),
    ("BOOLEAN", "boolean", []),
    ("THREAD", "virel.ruby.Thread", [("objectId", "LONG"), ("name", "STRING")]),
    ("FUNCTION", "virel.ruby.Function", [("name", "STRING"), ("filename", "STRING")]),
    ("LOCATION", "virel.ruby.Location", [("function", "FUNCTION", "pool"), ("line", "LONG")]),
    ("STACK", "virel.ruby.Stack", [("locations", "LOCATION", "pool", "array")]),
    ("SAMPLE", "virel.ruby.Sample", [
        ("startTime", "LONG"), ("sequence", "LONG"), ("thread", "THREAD", "pool"),
        ("stack", "STACK", "pool"), ("truncated", "BOOLEAN"), ("cpuTime", "LONG"),
        ("cpuDelta", "LONG"), ("wallDelta", "LONG"),
    ]),
]
IDS = {symbol: BASE + index for index, (symbol, _, _) in enumerate(TYPES)}


def varint(value):
    result = bytearray()
    for _ in range(8):
        if value < 128:
            return result + bytes([value])
        result.append((value & 127) | 128)
        value >>= 7
    return result + bytes([value])


def metadata():
    classes = []
    for symbol, name, fields in TYPES:
        attributes = {"name": name, "id": str(IDS[symbol])}
        if symbol == "SAMPLE":
            attributes["superType"] = "virel.Event"
        children = []
        for field_name, field_type, *options in fields:
            field = {"name": field_name, "class": str(IDS[field_type])}
            if "pool" in options:
                field["constantPool"] = "true"
            if "array" in options:
                field["dimension"] = "1"
            children.append(("field", field, []))
        classes.append(("class", attributes, children))
    classes.append(("class", {"name": "virel.eos", "id": "8", "superType": "virel.Event"}, []))
    root = ("root", {}, [("metadata", {}, classes), ("region", {}, [])])
    strings = []

    def intern(value):
        if value not in strings:
            strings.append(value)
        return varint(strings.index(value))

    def element(node):
        name, attributes, children = node
        result = intern(name) + varint(len(attributes))
        for key, value in attributes.items():
            result += intern(key) + intern(value)
        result += varint(len(children))
        for child in children:
            result += element(child)
        return result

    tree = element(root)
    payload = bytearray([0, 0, 0, 1, 0]) + varint(len(strings))
    for string in strings:
        encoded = string.encode("utf-8")
        payload += bytes([3]) + varint(len(encoded)) + encoded
    payload += tree
    size = len(payload) + 4
    return bytes([(size & 127) | 128, ((size >> 7) & 127) | 128, ((size >> 14) & 127) | 128, size >> 21]) + payload


def main():
    data = metadata()
    lines = ["#pragma once", "", "// Generated by tools/virel/generate_metadata.py; edit the schema there.", "enum {"]
    lines += [f"  VIREL_{name} = {value}," for name, value in IDS.items()]
    lines += ["};", "", "static const uint8_t virel_metadata[] = {"]
    lines += ["  " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 16]) + "," for offset in range(0, len(data), 16)]
    lines += ["};", ""]
    target = Path(__file__).resolve().parents[2] / "ext/datadog_profiling_native_extension/miteruby/virel_metadata.h"
    target.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
